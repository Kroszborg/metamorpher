// ── Lookups ───────────────────────────────────────────────────────────────

const bySlug = new Map<string, ToolDefinition>();
for (const tool of TOOLS) {
  if (bySlug.has(tool.slug)) throw new Error(`Duplicate tool slug in registry: ${tool.slug}`);
  bySlug.set(tool.slug, tool);
}

/** Every shipped tool, in registry order. */
export const AVAILABLE_TOOLS: readonly AvailableTool[] = TOOLS.filter(
  (t): t is AvailableTool => t.status === 'available',
);

export function getTool(slug: string): ToolDefinition | undefined {
  return bySlug.get(slug);
}

export function getAvailableTool(slug: string): AvailableTool | undefined {
  const tool = bySlug.get(slug);
  return tool?.status === 'available' ? tool : undefined;
}

export function toolsInCategory(id: CategoryId): AvailableTool[] {
  return AVAILABLE_TOOLS.filter((t) => t.category === id);
}

/** Categories with at least one available tool, in display order. */
export function activeCategories(): Category[] {
  return CATEGORIES.filter((c) => AVAILABLE_TOOLS.some((t) => t.category === c.id));
}

/** Strips the loader so the result can cross the server/client boundary. */
export function toInfo(tool: ToolDefinition): ToolInfo {
  const { load: _load, ...info } = tool;
  return info;
}

